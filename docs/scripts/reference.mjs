// Regenerates the generated part of docs/language/reference.mdx from the API
// pages, the type pages' field tables, and the SKY130 library's doc comments.
// Run it from docs/ with `node scripts/reference.mjs`; `--check` exits 1
// instead of writing when the page is out of date.
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const docs = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs');
const sky130 = join(docs, '..', '..', 'pdks', 'sky130', 'lib.ar');
const target = join(docs, 'language', 'reference.mdx');
const START = '{/* generated:start */}';
const END = '{/* generated:end */}';

const TYPES = [
  ['Rect', 'types/rect', 0],
  ['Polygon', 'types/polygon', 0],
  ['Path', 'types/path', 0],
  ['Point', 'types/point', 0],
  ['Inst', 'types/instance', 0],
  ['SchematicInst', 'types/instance', 1],
];

const SECTIONS = [
  ['`std::layout`', 'std-layout', ['std-layout']],
  ['`std::schematic`', 'std-schematic', ['std-schematic']],
  ['`std`', 'std', ['std']],
  [
    'Built-in functions',
    'builtins',
    ['builtins/constraints', 'builtins/math', 'builtins/collections', 'builtins/vias'],
  ],
];

const read = (page) => readFileSync(join(docs, 'language', `${page}.mdx`), 'utf8');

// One `- signature: summary` line per <ApiItem> on a page.
function apiItems(page) {
  const text = read(page);
  const item =
    /<ApiItem\s+id="[^"]+"\s+name="[^"]+"\s+signature=\{'((?:[^'\\]|\\.)*)'\}\s+summary=\{<>([\s\S]*?)<\/>\}/g;
  const lines = [...text.matchAll(item)].map(
    ([, signature, summary]) =>
      `- \`${signature.replace(/\\'/g, "'")}\`: ${summary.replace(/\s+/g, ' ').trim()}`,
  );
  const count = text.split('<ApiItem').length - 1;
  if (lines.length !== count) {
    throw new Error(`${page}: parsed ${lines.length} of ${count} ApiItems`);
  }
  return lines;
}

// A type's fields, grouped by type in table order: `x0`, `y0`: `Float`; ...
function fields(name, page, index) {
  const table = read(page).split('<FieldTable')[index + 1].split(']}')[0];
  const groups = [];
  for (const [, field, type] of table.matchAll(/\{name: '([^']+)', type: '([^']+)'/g)) {
    const last = groups.at(-1);
    if (last && last.type === type) last.names.push(field);
    else groups.push({type, names: [field]});
  }
  const list = groups
    .map(({type, names}) => `${names.map((n) => `\`${n}\``).join(', ')}: ${type}`)
    .join('; ');
  return `- [\`${name}\`](/language/${page}): ${list}.`;
}

// Each documented cell or function in the SKY130 library: its signature, the
// first sentence of its doc comment, and a cell's public fields.
function sky130Items() {
  const lines = readFileSync(sky130, 'utf8').split('\n');
  const items = [];
  for (let i = 0; i < lines.length; i++) {
    // A declaration whose parameters span several lines ends at the line with `{`.
    let last = i;
    if (/^(cell|fn) \w+(<[^>]*>)?\($/.test(lines[i])) {
      while (last < lines.length - 1 && !lines[last].endsWith('{')) last++;
    }
    const text = lines
      .slice(i, last + 1)
      .map((l) => l.trim())
      .join(' ')
      .replace(/\( /, '(')
      .replace(/,? \)/, ')');
    const decl = text.match(/^(cell|fn) (.*?)\s*\{$/);
    if (!decl || !lines[i - 1]?.startsWith('///')) continue;
    let start = i;
    while (lines[start - 1]?.startsWith('///')) start--;
    const doc = lines
      .slice(start, i)
      .map((l) => l.replace(/^\/\/\/ ?/, ''))
      .join('\n')
      .split('\n\n')[0]
      .replace(/\s+/g, ' ');
    const sentence = doc.match(/^.*?\.(?=\s+[A-Z`]|$)/)[0];
    let end = last + 1;
    while (lines[end] !== '}') end++;
    const pub = [...lines.slice(i, end).join('\n').matchAll(/pub let (\w+)/g)].map((m) => `\`${m[1]}\``);
    const extra = pub.length ? ` Fields: ${pub.join(', ')}.` : '';
    items.push(`- \`sky130::${decl[2]}\`: ${sentence}${extra}`);
  }
  return items;
}

function generate() {
  const out = [
    START,
    '{/* Generated by docs/scripts/reference.mjs; edit the pages it reads instead. */}',
    '',
    '## Types',
    '',
    ...TYPES.map((t) => fields(...t)),
  ];
  for (const [title, link, pages] of SECTIONS) {
    out.push('', `## [${title}](/language/${link})`, '', ...pages.flatMap(apiItems));
  }
  out.push('', '## [SKY130 library](/language/sky130)', '', ...sky130Items(), '', END);
  return out.join('\n');
}

const current = readFileSync(target, 'utf8');
const [head, rest] = current.split(START);
if (rest === undefined || !rest.includes(END)) {
  throw new Error(`${target} lacks the ${START} and ${END} markers`);
}
const updated = head + generate() + rest.split(END)[1];
if (process.argv.includes('--check')) {
  if (updated !== current) {
    console.error('docs/language/reference.mdx is out of date; run `node scripts/reference.mjs` in docs/.');
    process.exit(1);
  }
} else if (updated !== current) {
  writeFileSync(target, updated);
}
